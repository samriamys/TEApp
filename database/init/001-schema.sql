-- Minimal local schema inferred from Palabra and PalabraRepository.
-- The PostgreSQL image applies this only when its data directory is empty.
-- Import real vocabulary/media separately; this file does not seed content.
BEGIN;

CREATE TABLE vocal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    letra VARCHAR(1) NOT NULL UNIQUE
);

CREATE TABLE palabra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(255) NOT NULL,
    dificultad INTEGER NOT NULL,
    vocal_id BIGINT NOT NULL REFERENCES vocal(id)
);

CREATE TABLE recurso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    palabra_id BIGINT NOT NULL REFERENCES palabra(id),
    url_imagen TEXT NOT NULL,
    url_audio TEXT NOT NULL
);

CREATE INDEX palabra_vocal_dificultad_idx ON palabra (vocal_id, dificultad);
CREATE INDEX recurso_palabra_idx ON recurso (palabra_id);

COMMIT;
