-- Baseline for a new local database. Vocabulary and media are imported separately.
BEGIN;

CREATE TABLE palabra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(255) NOT NULL,
    dificultad INTEGER NOT NULL,
    vocal VARCHAR(1) NOT NULL,
    url_imagen TEXT,
    url_audio TEXT
);

CREATE INDEX palabra_vocal_dificultad_idx ON palabra (vocal, dificultad);

COMMIT;
